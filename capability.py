"""Capability battery: does an intervention make the model better or worse at a task? (Q8, functional personas)

Every item is multiple choice with four lettered options. The model sees the chat prompt and is scored on its very
next token: the item is correct when the right letter has the highest probability among A-D, and the margin is that
letter's log-probability minus the log-sum-exp of the other three. No sampling, no parsing.

Most items are generated by seeded code (arithmetic, letter counting, misspellings, number sequences), so every answer
key is right by construction; the facts are hand-written. Items alternate between two halves: hits are looked for on
half "a" and confirmed on half "b".

    families: arithmetic (2-digit x 2-digit products), letters (count a letter in a word), spelling (find the
    misspelled word), sequence (next number), facts (general knowledge)
"""

import random
from dataclasses import dataclass

import numpy as np
import torch

from steer import Intervention, Steerer

LETTERS = "ABCD"
SEED = 7


@dataclass(frozen=True)
class Item:
    family: str
    question: str
    options: tuple[str, str, str, str]
    answer: int  # index of the correct option
    half: str  # "a" (discovery) or "b" (confirmation)

    def prompt(self) -> str:
        lines = [self.question, ""] + [f"{LETTERS[i]}) {o}" for i, o in enumerate(self.options)]
        return "\n".join(lines + ["", "Answer with the letter only."])


def _mc(rng: random.Random, correct, distractors) -> tuple[tuple, int]:
    options = [correct] + list(distractors)
    rng.shuffle(options)
    return tuple(str(o) for o in options), options.index(correct)


def arithmetic(rng, n):
    for _ in range(n):
        a, b = rng.randint(13, 98), rng.randint(13, 98)
        c = a * b
        wrong = {c + 10, c - 10, c + 1, c - 1, c + 100, c - 100, int(str(c)[::-1]) if str(c)[::-1] != str(c) else c + 20}
        wrong.discard(c)
        yield "arithmetic", f"What is {a} x {b}?", *_mc(rng, c, rng.sample(sorted(wrong), 3))


WORDS = ["strawberry", "banana", "mississippi", "bookkeeper", "committee", "accommodate", "parallel", "occurrence",
         "embarrass", "necessary", "possession", "assessment", "millennium", "referee", "balloon", "coffee", "pepper",
         "letter", "address", "success", "tomorrow", "giraffe", "rhythm", "cinnamon", "hippopotamus", "tennessee",
         "programming", "engineering", "chocolate", "elephant", "independence", "beekeeper", "aardvark", "parrot"]


def letters(rng, n):
    pairs = [(w, ch) for w in WORDS for ch in sorted(set(w)) if w.count(ch) >= 2]
    for word, ch in rng.sample(pairs, n):
        c = word.count(ch)
        wrong = [x for x in (c - 1, c + 1, c + 2, c - 2) if x > 0][:3]
        yield "letters", f"How many times does the letter '{ch}' appear in the word '{word}'?", *_mc(rng, c, wrong)


