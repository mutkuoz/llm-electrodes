def _misspell(rng, word):
    i = rng.randrange(1, len(word) - 2)
    return word[:i] + word[i + 1] + word[i] + word[i + 2 :]


def spelling(rng, n):
    for _ in range(n):
        words = rng.choice(SENTENCES).split()
        candidates = [i for i, w in enumerate(words) if len(w) >= 6]
        target = rng.choice(candidates)
        wrong = _misspell(rng, words[target])
        while wrong == words[target]:
            wrong = _misspell(rng, words[target])
        shown = words[:target] + [wrong] + words[target + 1 :]
        others = rng.sample([w for i, w in enumerate(shown) if i != target and len(w) >= 4], 3)
        question = f'Which word in this sentence is misspelled?\n"{" ".join(shown)}."'
        yield "spelling", question, *_mc(rng, wrong, others)


def sequence(rng, n):
    kinds = ["add", "mul", "square", "fib", "alt"]
    for _ in range(n):
        kind = rng.choice(kinds)
        if kind == "add":
            a, d = rng.randint(2, 40), rng.randint(3, 17)
            seq = [a + d * i for i in range(6)]
        elif kind == "mul":
            a, r = rng.randint(2, 6), rng.choice([2, 3])
            seq = [a * r**i for i in range(6)]
        elif kind == "square":
            a = rng.randint(1, 6)
            seq = [(a + i) ** 2 for i in range(6)]
        elif kind == "fib":
            x, y = rng.randint(1, 5), rng.randint(2, 7)
            seq = [x, y]
            while len(seq) < 6:
                seq.append(seq[-1] + seq[-2])
        else:
            a, d, e = rng.randint(5, 30), rng.randint(2, 9), rng.randint(1, 4)
            seq = [a]
            for i in range(5):
                seq.append(seq[-1] + (d if i % 2 == 0 else -e))
        shown, c = seq[:5], seq[5]
        wrong = sorted({c + 1, c - 1, c + 2, c - 2, c + seq[4] - seq[3]} - {c})
        yield "sequence", f"What number comes next? {', '.join(map(str, shown))}, ...", *_mc(rng, c, rng.sample(wrong, 3))


