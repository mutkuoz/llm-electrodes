def facts(rng, n):
    for question, correct, wrong in FACTS[:n]:
        yield "facts", question, *_mc(rng, correct, wrong)


def battery() -> list[Item]:
    """The fixed battery: 40 arithmetic, 30 letters, 40 spelling, 40 sequence, 30 facts; halves alternate."""
    rng = random.Random(SEED)
    items = []
    for family in (arithmetic(rng, 40), letters(rng, 30), spelling(rng, 40), sequence(rng, 40), facts(rng, 30)):
        for i, (name, question, options, answer) in enumerate(family):
            items.append(Item(name, question, options, answer, "ab"[i % 2]))
    return items


@torch.inference_mode()
def score_items(steerer: Steerer, items: list[Item], rows: list[list[Intervention]], batch: int = 32) -> dict:
    """Per row and item, whether the right letter wins and its margin. Row 0 of every batch is plain, so the plain
    model is scored with exactly the batch shape every steered row is scored with.

    Returns {"correct": (len(rows) + 1, items) bool, "margin": (len(rows) + 1, items) float}, plain first.
    """
    letter_ids = [steerer.tokenizer(c, add_special_tokens=False).input_ids[0] for c in LETTERS]
    head = steerer.model.get_output_embeddings()
    correct = np.zeros((len(rows) + 1, len(items)), dtype=bool)
    margin = np.zeros((len(rows) + 1, len(items)), dtype=np.float32)
    with steerer.lock:
        for j, item in enumerate(items):
            ids = torch.tensor([steerer.prompt_ids([{"role": "user", "content": item.prompt()}])], device=steerer.model.device)
            ids = ids.expand(batch, -1)
            for start in range(0, max(len(rows), 1), batch - 1):
                chunk = rows[start : start + batch - 1]
                padded = [[], *chunk] + [[]] * (batch - 1 - len(chunk))
                with steerer.steering(padded):
                    last = steerer.model.model(input_ids=ids, use_cache=False).last_hidden_state[:, -1]
                logp = head(last).float().log_softmax(-1)[:, letter_ids]  # (batch, 4)
                picks = logp.argmax(-1).cpu().numpy() == item.answer
                others = torch.cat([logp[:, :item.answer], logp[:, item.answer + 1 :]], 1)
                margins = (logp[:, item.answer] - torch.logsumexp(others, 1)).cpu().numpy()
                if start == 0:
                    correct[0, j], margin[0, j] = picks[0], margins[0]
                n = len(chunk)
                correct[1 + start : 1 + start + n, j] = picks[1 : 1 + n]
                margin[1 + start : 1 + start + n, j] = margins[1 : 1 + n]
    return {"correct": correct, "margin": margin}
